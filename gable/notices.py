#!/usr/bin/env python3
"""Write Gable's modification notices into the files changed since a base tag.

LGPL 2.1 section 2(b) requires each modified file to carry a prominent notice
that it was changed, with the date of every change. For each upstream file
that differs from the base tag, including one Git sees as renamed or copied,
this writes a comment block at the top of the file listing every commit that
changed it, with its date. It also regenerates the per-file list in
GABLE-MODIFICATIONS.md, which also lists the upstream files that were deleted
and those whose format has no comment syntax, such as JSON or expected test
output; for those files the list is the notice.

Run it with every change to a base branch, and commit the result with it:

    gable/notices.py --base v2.0.0

`--check` exits with status 1, changing nothing, when any notice is missing or
out of date. Files Gable added outright are not modified upstream files and get
no notice.

`--uncommitted SUBJECT` also counts uncommitted changes to tracked files, as one
change dated today and described by SUBJECT. A release uses it after stamping
its version into upstream's src/core/Version.ml, so the source it publishes
carries a notice for that change too.
"""

import argparse
import datetime
import re
import subprocess
import sys
from pathlib import Path

BEGIN = "Gable modification notice."
END = "End of Gable modification notice."
NOTICE_COMMIT = "Add Gable modification notices"
MODIFICATIONS = Path("GABLE-MODIFICATIONS.md")
FILES_BEGIN = "<!-- Generated by gable/notices.py: begin -->"
FILES_END = "<!-- Generated by gable/notices.py: end -->"

# Paths that belong to the fork itself rather than to upstream OpenGrep.
GABLE_PATHS = ("GABLE.md", "GABLE-MODIFICATIONS.md", "gable/", ".github/workflows/gable-")


def git(*args):
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout


def changed_paths(*diff_args):
    """{path: (status, origin)} of upstream files that `git diff` reports as changed.

    Status is M (modified), R (renamed), C (copied) or D (deleted); origin is the
    path a renamed or copied file came from. Added files are Gable's own.
    """
    found = {}
    for line in git("diff", "--name-status", "-M", "-C", *diff_args).splitlines():
        fields = line.split("\t")
        status = fields[0][0]
        if status in ("R", "C"):
            origin, path = fields[1], fields[2]
        elif status in ("M", "T", "D"):
            origin, path = None, fields[1]
            status = "M" if status == "T" else status
        else:
            continue
        if not path.startswith(GABLE_PATHS):
            found[path] = (status, origin)
    return found


def changes(base, path, status):
    """The (date, subject) of each commit since `base` that changed `path`, oldest first."""
    # --follow and --reverse together stop following at the rename, losing
    # the earlier changes, so the newest-first log is reversed here instead.
    follow = ["--follow"] if status in ("R", "C") else []
    log = git("log", *follow, "--date=short", "--format=%ad%x09%s", f"{base}..HEAD", "--", path)
    entries = [tuple(line.split("\t", 1)) for line in reversed(log.splitlines())]
    return [(date, subject) for date, subject in entries if subject != NOTICE_COMMIT]


def comment_style(path):
    """How to write a comment block at the top of `path`."""
    suffix = Path(path).suffix
    if suffix in (".ml", ".mli", ".mll", ".atd"):
        return "ocaml"
    if suffix == ".mly":
        return "menhir"
    if suffix in (".ts", ".tsx", ".js", ".jsx", ".java", ".c", ".h", ".cpp", ".go", ".rs", ".scala", ".kt", ".swift", ".cs"):
        return "slash"
    if Path(path).name in ("dune", "dune-project", "dune-workspace"):
        return "semicolon"
    if suffix in (".py", ".rb", ".sh", ".yaml", ".yml") or Path(path).name == "Makefile":
        return "hash"
    return None


def notice_lines(entity, entries):
    lines = [f"{BEGIN} This file was changed by {entity}:"]
    lines += [f"  {date}  {subject}" for date, subject in entries]
    lines.append(f"See GABLE-MODIFICATIONS.md. {END}")
    return lines


def render(style, lines):
    if style in ("ocaml", "menhir"):
        body = "\n   ".join(lines)
        return f"(* {body} *)\n"
    prefix = {"slash": "//", "semicolon": ";", "hash": "#"}[style]
    return "".join(f"{prefix} {line}\n" for line in lines)


# A notice already in a file, whatever its comment style, up to and including its end marker.
EXISTING = re.compile(r"^(?:\(\* |// |; |# )" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"(?: \*\))?\n", re.S | re.M)


def with_notice(text, style, notice):
    """`text` with `notice` at its top, replacing any notice already there."""
    text = EXISTING.sub("", text, count=1)
    head = ""
    if style == "menhir" and text.startswith("%{\n"):
        # The grammar opens with its OCaml header; the notice goes inside it.
        head, text = "%{\n", text[len("%{\n"):]
    elif style == "hash" and text.startswith("#!"):
        newline = text.index("\n") + 1
        head, text = text[:newline], text[newline:]
    return head + notice + text


def describe(path, status, origin, style):
    """The table's File cell for `path`."""
    cell = f"`{path}`"
    if status == "R":
        cell += f" (renamed from `{origin}`)"
    elif status == "C":
        cell += f" (copied from `{origin}`)"
    elif status == "D":
        cell += " (deleted)"
    if status != "D" and style is None:
        cell += " (no comment syntax; this list is its notice)"
    return cell


def files_section(base, files):
    if not files:
        return "\n".join([FILES_BEGIN, "", f"No files are changed since `{base}`.", "", FILES_END])
    rows = ["| File | Changes |", "| --- | --- |"]
    for cell, entries in files:
        listed = "<br>".join(f"{date} {subject}" for date, subject in entries)
        rows.append(f"| {cell} | {listed} |")
    return "\n".join([FILES_BEGIN, "", f"Files changed since `{base}`, with each change and its date:", "", *rows, "", FILES_END])


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base", required=True, help="the upstream tag the base branch starts from")
    parser.add_argument("--entity", default="Gable.ai", help="the name the notices give for who made the changes")
    parser.add_argument("--check", action="store_true", help="report missing or stale notices without changing files")
    parser.add_argument("--uncommitted", metavar="SUBJECT",
                        help="also count uncommitted changes to tracked files, as one change dated today")
    args = parser.parse_args()

    committed = changed_paths(args.base, "HEAD")
    uncommitted = changed_paths("HEAD") if args.uncommitted else {}
    stale = []
    files = []
    for path in sorted(committed.keys() | uncommitted.keys()):
        status, origin = committed.get(path) or uncommitted[path]
        style = comment_style(path)
        entries = changes(args.base, path, status) if path in committed else []
        if path in uncommitted:
            entries.append((datetime.date.today().isoformat(), args.uncommitted))
        files.append((describe(path, status, origin, style), entries))
        if status == "D" or style is None:
            continue
        text = Path(path).read_text()
        updated = with_notice(text, style, render(style, notice_lines(args.entity, entries)))
        if updated != text:
            stale.append(path)
            if not args.check:
                Path(path).write_text(updated)

    section = files_section(args.base, files)
    document = MODIFICATIONS.read_text()
    pattern = re.compile(re.escape(FILES_BEGIN) + r".*?" + re.escape(FILES_END), re.S)
    updated = pattern.sub(lambda _: section, document) if pattern.search(document) else document.rstrip("\n") + "\n\n" + section + "\n"
    if updated != document:
        stale.append(str(MODIFICATIONS))
        if not args.check:
            MODIFICATIONS.write_text(updated)

    for path in stale:
        print(("stale: " if args.check else "updated: ") + path)
    if args.check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
